from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data" / "processed"
FIGURES = ROOT / "results" / "figures"

SUMMARY_PATHS = {
    "Greedy append-only": DATA / "baseline_summary.json",
    "Route insertion": DATA / "insertion_summary.json",
    "Local search": DATA / "local_search_summary.json",
}
ENHANCED_SUMMARY_PATH = DATA / "enhanced_local_search_summary.json"

st.set_page_config(
    page_title="Field-Service Scheduling Dashboard",
    page_icon="📊",
    layout="wide",
)

st.title("Field-Service Scheduling Optimizer")
st.caption("Offline dashboard for baseline schedulers, enhanced route-order search, and duration/cancellation experiments.")

missing = [path for path in SUMMARY_PATHS.values() if not path.exists()]
DEMO_SUMMARY_PATH = ROOT / "results" / "scheduler_demo_summary.json"
summary_source = ""

try:
    if not missing:
        summaries = {
            label: json.loads(path.read_text(encoding="utf-8"))
            for label, path in SUMMARY_PATHS.items()
        }
        if ENHANCED_SUMMARY_PATH.exists():
            enhanced_summary = json.loads(ENHANCED_SUMMARY_PATH.read_text(encoding="utf-8"))
            
            enhanced_summary.setdefault(
                "total_travel_minutes_including_depot_returns",
                enhanced_summary.get("final_travel_minutes_including_depot_returns"),
            )
            
            
            if enhanced_summary.get("total_service_minutes") is None:
                enhanced_routes_path = DATA / "enhanced_local_search_routes.csv"
                if enhanced_routes_path.exists():
                    enhanced_routes = pd.read_csv(enhanced_routes_path)
                    if "duration_minutes" in enhanced_routes.columns:
                        enhanced_summary["total_service_minutes"] = int(
                            pd.to_numeric(
                                enhanced_routes["duration_minutes"], errors="coerce"
                            ).fillna(0).sum()
                        )
            enhanced_summary.setdefault("total_service_minutes", None)
            summaries["Enhanced local search"] = enhanced_summary
        summary_source = "local generated scheduler summaries"
    else:
        if not DEMO_SUMMARY_PATH.exists():
            st.error("Scheduler summaries and the aggregate demo summary are missing.")
            st.write("The dashboard will not launch or recompute any scheduling algorithm automatically.")
            st.write("Missing local files:")
            for path in missing:
                st.code(str(path.relative_to(ROOT)))
            st.stop()
        demo_payload = json.loads(DEMO_SUMMARY_PATH.read_text(encoding="utf-8"))
        summaries = demo_payload["summaries"]
        summary_source = "committed aggregate demonstration summary"
        st.info(
            "Showing the committed aggregate demonstration results because local scheduler "
            "summaries are not present. This enables the overview without rerunning any scheduler. "
            "The Route Explorer needs local task/route CSV files generated by the validated pipeline."
        )

    required_keys = {
        "assigned_tasks",
        "unassigned_tasks",
        "active_task_coverage",
        "technician_routes_used",
        "total_travel_minutes_including_depot_returns",
    }
    for label, summary in summaries.items():
        absent = required_keys.difference(summary)
        if absent:
            raise ValueError(f"{label} summary is missing keys: {', '.join(sorted(absent))}")
    for label in SUMMARY_PATHS:
        if label not in summaries:
            raise ValueError(f"Summary missing scheduler method: {label}")
except (OSError, json.JSONDecodeError, ValueError, KeyError, TypeError) as error:
    st.error(f"Unable to read scheduler summaries: {error}")
    st.stop()

st.caption(f"Scheduling summary source: {summary_source}")

travel_key = "total_travel_minutes_including_depot_returns"
method_order = ["Greedy append-only", "Route insertion", "Local search"]
if "Enhanced local search" in summaries:
    method_order.append("Enhanced local search")
records: list[dict[str, object]] = []

for label in method_order:
    item = summaries[label]
    assigned = int(item["assigned_tasks"])
    unassigned = int(item["unassigned_tasks"])
    active = int(item.get("active_tasks", assigned + unassigned))
    records.append(
        {
            "Scheduler": label,
            "Tasks assigned": assigned,
            "Active tasks": active,
            "Coverage (%)": float(item["active_task_coverage"]) * 100,
            "Tasks unassigned": unassigned,
            "Routes used": int(item["technician_routes_used"]),
            "Travel (min)": float(item[travel_key]),
            "Service (min)": (
                int(item["total_service_minutes"])
                if item.get("total_service_minutes") is not None else None
            ),
        }
    )

comparison = pd.DataFrame(records)
greedy = summaries["Greedy append-only"]
insertion = summaries["Route insertion"]
local_search = summaries["Local search"]

greedy_travel = float(greedy[travel_key])
insertion_travel = float(insertion[travel_key])
local_travel = float(local_search[travel_key])
saved_vs_greedy = greedy_travel - local_travel
saved_vs_insertion = insertion_travel - local_travel
saved_pct = (saved_vs_greedy / greedy_travel * 100) if greedy_travel else 0.0
insertion_saved_pct = (
    saved_vs_insertion / insertion_travel * 100 if insertion_travel else 0.0
)

tab_overview, tab_routes, tab_ml = st.tabs(
    ["Scheduling overview", "Route explorer", "ML experiments"]
)

with tab_overview:
    best_label = "Enhanced local search" if "Enhanced local search" in summaries else "Local search"
    best_summary = summaries[best_label]
    st.subheader(f"Current best scheduling result — {best_label}")
    active_tasks = int(best_summary.get("active_tasks", 2233))
    assigned_tasks = int(best_summary["assigned_tasks"])
    unassigned_tasks = int(best_summary["unassigned_tasks"])
    routes_used = int(best_summary["technician_routes_used"])
    best_travel = float(best_summary[travel_key])

    m1, m2, m3, m4 = st.columns(4)
    best_saved_vs_greedy = greedy_travel - best_travel
    best_saved_pct = (best_saved_vs_greedy / greedy_travel * 100) if greedy_travel else 0.0
    m1.metric("Estimated travel", f"{best_travel:,.0f} min")
    m2.metric(
        "Travel reduction vs greedy",
        f"{best_saved_pct:.2f}%",
        delta=f"{best_saved_vs_greedy:,.0f} minutes saved",
        delta_color="off",
    )
    m3.metric("Active tasks assigned", f"{assigned_tasks:,} / {active_tasks:,}")
    m4.metric("Technician-day routes", f"{routes_used:,}")

    best_saved_vs_insertion = insertion_travel - best_travel
    best_saved_vs_insertion_pct = (best_saved_vs_insertion / insertion_travel * 100) if insertion_travel else 0.0
    st.markdown(
        f"**{best_label}** reduces travel by **{best_saved_vs_insertion:,.0f} minutes "
        f"({best_saved_vs_insertion_pct:.2f}%)** compared with route insertion, with the same "
        f"number of assigned tasks."
    )
    st.caption(
        "Travel includes the final return-to-depot leg. Service duration is reported "
        "separately. Scheduling methods are heuristics, not guaranteed optimal solutions."
    )

    st.subheader("Compare available scheduling methods")
    st.dataframe(
        comparison,
        hide_index=True,
        use_container_width=True,
        column_config={
            "Coverage (%)": st.column_config.NumberColumn(format="%.2f%%"),
            "Travel (min)": st.column_config.NumberColumn(format="%,.0f"),
            "Service (min)": st.column_config.NumberColumn(format="%,.0f"),
        },
    )

    left, right = st.columns(2)
    with left:
        st.markdown("#### Estimated travel time")
        travel_chart = comparison.set_index("Scheduler")[["Travel (min)"]]
        st.bar_chart(travel_chart)
    with right:
        st.markdown("#### Active-task coverage")
        coverage_chart = comparison.set_index("Scheduler")[["Coverage (%)"]]
        st.bar_chart(coverage_chart)

    st.markdown("#### Saved comparison plots")
    st.caption("These plots are generated by src/compare_schedulers.py and include enhanced local search whenever its validated local summary is available. Rerun that script after regenerating scheduler outputs.")
    plot_columns = st.columns(3)
    plots = [
        ("travel_time_comparison.png", "Travel time"),
        ("task_coverage_comparison.png", "Task coverage"),
        ("routes_used_comparison.png", "Routes used"),
    ]
    for column, (filename, label) in zip(plot_columns, plots):
        image_path = FIGURES / filename
        with column:
            if image_path.exists():
                st.image(str(image_path), caption=label, use_container_width=True)
            else:
                st.info(f"{filename} not found. Run python src/compare_schedulers.py to regenerate the baseline comparison plot.")

    st.download_button(
        "Download comparison table (CSV)",
        data=comparison.to_csv(index=False).encode("utf-8"),
        file_name="scheduler_comparison_dashboard.csv",
        mime="text/csv",
    )

with tab_routes:
    st.subheader("Inspect a saved local-search schedule")
    enhanced_routes_path = DATA / "enhanced_local_search_routes.csv"
    enhanced_status_path = DATA / "enhanced_local_search_task_status.csv"
    if "Enhanced local search" in summaries and enhanced_routes_path.exists():
        routes_path, status_path = enhanced_routes_path, enhanced_status_path
        st.caption("Showing the enhanced local-search route order.")
    else:
        routes_path = DATA / "local_search_routes.csv"
        status_path = DATA / "local_search_task_status.csv"

    if routes_path.exists():
        try:
            routes_df = pd.read_csv(routes_path, keep_default_na=False)
        except (OSError, pd.errors.ParserError, UnicodeDecodeError) as error:
            st.error(f"Could not read local-search route assignments: {error}")
        else:
            if routes_df.empty:
                st.info("The local-search route file is empty.")
            else:
                routes_df["technician_id"] = pd.to_numeric(
                    routes_df["technician_id"], errors="coerce"
                )
                route_ids = sorted(
                    int(value)
                    for value in routes_df["technician_id"].dropna().unique()
                )
                route_sizes = routes_df.groupby("technician_id").size()
                largest_route_id = int(route_sizes.idxmax())
                default_route_index = route_ids.index(largest_route_id)
                chosen_technician = st.selectbox(
                    "Select technician-day ID",
                    route_ids,
                    index=default_route_index,
                    format_func=lambda value: (
                        f"Technician-day {value} ({int(route_sizes.get(value, 0))} tasks)"
                    ),
                )
                one_route = routes_df[
                    routes_df["technician_id"] == chosen_technician
                ].copy()
                one_route["route_sequence"] = pd.to_numeric(
                    one_route["route_sequence"], errors="coerce"
                )
                one_route = one_route.sort_values("route_sequence")

                inbound = pd.to_numeric(
                    one_route["inbound_travel_minutes"], errors="coerce"
                ).fillna(0).sum()
                returns = pd.to_numeric(
                    one_route["return_travel_minutes"], errors="coerce"
                ).fillna(0).sum()
                r1, r2, r3 = st.columns(3)
                r1.metric("Tasks in selected route", f"{len(one_route):,}")
                r2.metric("Inbound travel total", f"{inbound:,.0f} min")
                r3.metric("Return travel", f"{returns:,.0f} min")

                display_columns = [
                    column
                    for column in [
                        "route_sequence",
                        "task_id",
                        "service_start",
                        "service_finish",
                        "duration_minutes",
                        "inbound_travel_minutes",
                        "return_travel_minutes",
                    ]
                    if column in one_route.columns
                ]
                st.dataframe(
                    one_route[display_columns],
                    hide_index=True,
                    use_container_width=True,
                )

                st.download_button(
                    "Download selected route (CSV)",
                    data=one_route[display_columns].to_csv(index=False).encode("utf-8"),
                    file_name=f"local_search_route_technician_{chosen_technician}.csv",
                    mime="text/csv",
                )
    else:
        st.info(
            "Route assignments are not present yet. The dashboard can still show the "
            "saved aggregate comparison, but this tab needs data/processed/local_search_routes.csv."
        )

    if status_path.exists():
        st.markdown("#### Task assignment status")
        try:
            status_df = pd.read_csv(status_path, keep_default_na=False)
            status_values = sorted(status_df["status"].astype(str).unique().tolist())
            selected_status = st.selectbox(
                "Filter tasks by status",
                status_values,
                key="task_status_filter",
            )
            filtered = status_df[status_df["status"].astype(str) == selected_status]
            status_columns = [
                column
                for column in [
                    "task_id",
                    "status",
                    "reason",
                    "technician_id",
                    "service_start",
                    "service_finish",
                ]
                if column in filtered.columns
            ]
            st.caption(f"Showing {len(filtered):,} tasks with status '{selected_status}'.")
            st.dataframe(
                filtered[status_columns].head(200),
                hide_index=True,
                use_container_width=True,
            )
            if len(filtered) > 200:
                st.caption("Only the first 200 matching rows are shown here.")
        except (OSError, pd.errors.ParserError, UnicodeDecodeError, KeyError) as error:
            st.error(f"Could not load task status records: {error}")
    else:
        st.info("Task-status details are unavailable because the local status CSV is missing.")

with tab_ml:
    st.subheader("What the ML experiments currently show")
    st.write(
        "The ML work is exploratory. The best measured improvement so far comes from "
        "the scheduling heuristics above, not from an ML model changing the schedule."
    )

    duration_metrics_path = ROOT / "results" / "duration_temporal_metrics.json"
    cancellation_metrics_path = ROOT / "results" / "cancellation_temporal_metrics.json"
    ml_left, ml_right = st.columns(2)

    try:
        duration_metrics = json.loads(duration_metrics_path.read_text(encoding="utf-8"))
        ridge_mae = float(duration_metrics["models"]["Ridge regression"]["mae_minutes"])
        median_mae = float(duration_metrics["models"]["Median baseline"]["mae_minutes"])
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as error:
        ridge_mae = None
        median_mae = None
        with ml_left:
            st.warning(f"Duration metrics are unavailable: {error}")

    try:
        cancellation_metrics = json.loads(cancellation_metrics_path.read_text(encoding="utf-8"))
        rf_metrics = cancellation_metrics["models"]["Random forest"]
        cancelled_test_count = int(cancellation_metrics["test_class_counts"]["cancelled"])
        cancelled_detected = int(rf_metrics["true_positive"])
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as error:
        cancelled_test_count = None
        cancelled_detected = None
        with ml_right:
            st.warning(f"Cancellation metrics are unavailable: {error}")

    with ml_left:
        st.markdown("#### Task-duration regression")
        if ridge_mae is not None and median_mae is not None:
            st.metric("Ridge model MAE", f"{ridge_mae:.2f} minutes")
            st.metric("Median-baseline MAE", f"{median_mae:.2f} minutes")
        st.caption(
            "Evaluation uses a chronological holdout; the metric summarizes recorded-duration prediction error."
        )
    with ml_right:
        st.markdown("#### Cancellation prediction")
        if cancelled_detected is not None and cancelled_test_count is not None:
            st.metric(
                "Cancelled test tasks detected by Random Forest",
                f"{cancelled_detected} of {cancelled_test_count}",
            )
        st.caption(
            "Cancellation results are summarized using the chronological test set."
        )

with st.sidebar:
    st.header("About this project")
    st.write("**Project:** ML-Based Business Optimization for Plumbing Service Chains")
    st.write("**Scheduling methods:** greedy, route insertion, relocation local search, enhanced swap/2-opt (when available)")
    st.write("**Dashboard:** reads the saved scheduler and model result files.")
    st.write("Use the reported metrics to compare the methods and experiments.")
